def _svg(name: str, color: str, stroke: float) -> bytes:
    body = _SHAPES[name].replace('fill="C"', f'fill="{color}"')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>').encode()


def pixmap(name: str, color: str = "#1D1D22", size: int = 18, stroke: float = 1.8, dpr: float = 2.0) -> QPixmap:
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.transparent)
    r = QSvgRenderer(QByteArray(_svg(name, color, stroke)))
    p = QPainter(pm)
    r.render(p, QRectF(0, 0, size * dpr, size * dpr))
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str = "#1D1D22", size: int = 18, stroke: float = 1.8) -> QIcon:
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size, stroke), QIcon.Normal)
    ic.addPixmap(pixmap(name, "#B0B0B8", size, stroke), QIcon.Disabled)
    return ic
